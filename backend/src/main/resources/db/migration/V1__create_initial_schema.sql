
-- 1. Ingredient types
CREATE TABLE ingredient_type (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    max_capacity DECIMAL(12,3) NOT NULL,
    unit_of_measure VARCHAR(10) NOT NULL,

    CONSTRAINT chk_ingredient_type_capacity
        CHECK (max_capacity > 0),

    CONSTRAINT chk_ingredient_type_unit
        CHECK (unit_of_measure IN ('KG', 'L'))
);

-- 2. Ingredients
CREATE TABLE ingredient (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    ingredient_type_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ingredient_type
        FOREIGN KEY (ingredient_type_id)
        REFERENCES ingredient_type(id)
);

-- 3. Compartments
CREATE TABLE compartment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(10) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'EMPTY',
    current_type_id BIGINT,
    last_movement_at TIMESTAMP,

    CONSTRAINT fk_compartment_type
        FOREIGN KEY (current_type_id)
        REFERENCES ingredient_type(id),

    CONSTRAINT chk_compartment_status
        CHECK (status IN ('EMPTY', 'OCCUPIED', 'BLOCKED'))
);

-- 4. Application users
CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    login VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 5. Current stock by compartment and ingredient
CREATE TABLE compartment_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compartment_id BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,
    quantity DECIMAL(12,3) NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_stock_compartment
        FOREIGN KEY (compartment_id)
        REFERENCES compartment(id),

    CONSTRAINT fk_stock_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES ingredient(id),

    CONSTRAINT uq_compartment_ingredient
        UNIQUE (compartment_id, ingredient_id),

    CONSTRAINT chk_stock_quantity
        CHECK (quantity > 0)
);

-- 6. Stock movement history
CREATE TABLE stock_movement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    compartment_id BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,
    movement_type VARCHAR(20) NOT NULL,
    quantity DECIMAL(12,3) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_movement_user
        FOREIGN KEY (user_id)
        REFERENCES app_user(id),

    CONSTRAINT fk_movement_compartment
        FOREIGN KEY (compartment_id)
        REFERENCES compartment(id),

    CONSTRAINT fk_movement_ingredient
        FOREIGN KEY (ingredient_id)
        REFERENCES ingredient(id),

    CONSTRAINT chk_movement_type
        CHECK (movement_type IN ('INBOUND', 'OUTBOUND')),

    CONSTRAINT chk_movement_quantity
        CHECK (quantity > 0)
);

